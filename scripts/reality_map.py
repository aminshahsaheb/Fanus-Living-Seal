#!/usr/bin/env python3
"""Static reachability map for the `fanus/` package.

Question answered: which modules can actually run, starting from the real
entry points (the deployed API, the CLI, the benchmark runner)?

Method: parse every module with `ast`, follow import statements (including
imports inside functions), and walk the graph from each entry point.
Limits: dynamic imports (importlib, __import__) are NOT followed, and code
outside `fanus/` (scripts/, tools/) is not analysed. "Unreachable" therefore
means "no static import path from these entry points", not "proven dead".

Usage:  python3 scripts/reality_map.py          # rewrites docs/REALITY_MAP.md
"""
import ast
import os
import sys
from collections import defaultdict

ENTRY_POINTS = {
    "API (deployed app)": ["fanus.api.server"],
    "CLI": ["fanus.cli", "fanus.main"],
    "Benchmark runner": ["fanus.audit.benchmark_v3"],
}


def load_modules(base="."):
    mods = {}
    root = os.path.join(base, "fanus")
    for r, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        for f in files:
            if not f.endswith(".py"):
                continue
            path = os.path.join(r, f)
            rel = os.path.relpath(path, base)[:-3].replace(os.sep, ".")
            is_pkg = rel.endswith(".__init__")
            name = rel[:-9] if is_pkg else rel
            mods[name] = {"path": path, "is_pkg": is_pkg}
    return mods


def imports_of(path, name, is_pkg):
    pkg = name if is_pkg else name.rsplit(".", 1)[0]
    found = set()
    with open(path, encoding="utf-8") as fh:
        tree = ast.parse(fh.read())
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            for a in n.names:
                found.add(a.name)
        elif isinstance(n, ast.ImportFrom):
            base = n.module or ""
            if n.level:
                parts = pkg.split(".")
                parts = parts[: len(parts) - (n.level - 1)]
                base = ".".join(parts + ([n.module] if n.module else []))
            found.add(base)
            for a in n.names:
                found.add(base + "." + a.name)
    return found


def reachable(graph, mods, entries):
    seen, todo = set(), [e for e in entries if e in mods]
    while todo:
        m = todo.pop()
        if m in seen:
            continue
        seen.add(m)
        parts = m.split(".")
        for i in range(1, len(parts)):  # importing a.b.c also runs a/__init__, a.b/__init__
            parent = ".".join(parts[:i])
            if parent in mods:
                todo.append(parent)
        todo.extend(graph[m])
    return seen


def compute(base="."):
    mods = load_modules(base)
    graph = {
        m: {i for i in imports_of(info["path"], m, info["is_pkg"]) if i in mods}
        for m, info in mods.items()
    }
    real = {m for m, info in mods.items() if not info["is_pkg"]}
    per_entry = {label: reachable(graph, mods, eps) & real for label, eps in ENTRY_POINTS.items()}
    union = set().union(*per_entry.values())
    return {"real": real, "per_entry": per_entry, "union": union, "unreachable": sorted(real - union)}


def render(result):
    real, union, dead = result["real"], result["union"], result["unreachable"]
    lines = [
        "# Reality Map",
        "",
        "Which modules in `fanus/` can actually run, starting from the real entry points.",
        "Generated by `python3 scripts/reality_map.py` (static `ast` import analysis).",
        "",
        "**Limits:** dynamic imports are not followed and code outside `fanus/` is not analysed.",
        "\"Unreachable\" means no static import path from these entry points, not \"proven dead\".",
        "",
        "| Entry point | Modules reachable |",
        "|-------------|-------------------|",
    ]
    for label, eps in ENTRY_POINTS.items():
        lines.append(f"| {label} (`{'`, `'.join(eps)}`) | {len(result['per_entry'][label])} of {len(real)} |")
    lines += ["", f"**Reachable from at least one entry point: {len(union)} of {len(real)} modules. "
              f"Not reachable from any: {len(dead)}.**", ""]
    groups = defaultdict(list)
    for m in dead:
        pkg, leaf = m.rsplit(".", 1)
        groups[pkg].append(leaf)
    lines += ["## Not reachable from any entry point", ""]
    for pkg in sorted(groups):
        lines.append(f"- `{pkg}`: " + ", ".join(f"`{x}`" for x in groups[pkg]))
    lines += ["", "Regenerate after structural changes; `tests/test_reality_guard.py` keeps the dormant "
              "high-risk modules (autonomous git, self-rewriting code, dynamic plugin loading) unreachable.", ""]
    return "\n".join(lines)


def main():
    result = compute(".")
    out = os.path.join("docs", "REALITY_MAP.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(render(result))
    print(f"wrote {out}: {len(result['union'])} of {len(result['real'])} modules reachable, "
          f"{len(result['unreachable'])} not")


if __name__ == "__main__":
    sys.exit(main())
